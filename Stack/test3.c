/**
 * ===========================================================================
 * 文件名: test3.c
 * 描述:   链式栈的实现
 * 日期:   2025-12-21
 * ===========================================================================
 *
 * 功能说明:
 *   本文件实现了基于链表的栈（Linked Stack），包括：
 *   1. 栈的初始化（带头节点）
 *   2. 判断栈空
 *   3. 进栈（Push）操作
 *   4. 出栈（Pop）操作
 *   5. 获取栈顶元素
 *
 * 数据结构:
 *   采用单链表实现的链式栈
 *   使用头节点，栈顶在链表头部（便于插入和删除）
 *
 * 三种栈实现对比:
 *   ┌─────────┬─────────────────┬─────────────────┬─────────────────┐
 *   │ 特性    │ test1.c         │ test2.c         │ test3.c         │
 *   ├─────────┼─────────────────┼─────────────────┼─────────────────┤
 *   │ 存储    │ 静态数组        │ 动态数组        │ 链表            │
 *   │ 大小    │ 固定MAXSIZE     │ 固定MAXSIZE     │ 无限制          │
 *   │ 空间    │ 预分配          │ 预分配          │ 按需分配        │
 *   │ push/pop│ O(1)            │ O(1)            │ O(1)            │
 *   │ 内存    │ 连续            │ 连续            │ 不连续          │
 *   └─────────┴─────────────────┴─────────────────┴─────────────────┘
 *
 * 链式栈的优势:
 *   - 无固定大小限制，理论上可以无限增长
 *   - 不会出现栈满的情况（除非系统内存耗尽）
 *   - 节省空间（不需要预分配大量空间）
 *
 * 链式栈的劣势:
 *   - 每次push/pop都需要malloc/free，开销较大
 *   - 额外的指针开销（每个节点需要next指针）
 *   - 内存不连续，缓存性能较差
 *
 * 栈顶位置:
 *   链式栈的栈顶在链表头部（head->next指向栈顶）
 *   这样push和pop都是O(1)操作
 *
 * 示意图:
 *   head → [30] → [20] → [10] → NULL
 *   ↑栈顶         ↑栈底
 *
 * 使用方法:
 *   编译: gcc test3.c -o test3
 *   运行: ./test3 (Linux/Mac) 或 test3.exe (Windows)
 *
 * 难度: ⭐⭐（链表 + 栈的结合）
 * ===========================================================================
 */

#include <stdio.h>
#include <stdlib.h>

// 栈元素类型定义
typedef int ElemType;

/**
 * 链式栈节点结构定义
 *
 * 成员说明:
 *   - data: 节点存储的数据元素
 *   - next: 指向下一个节点的指针
 *
 * 结构说明:
 *   与单链表的节点结构完全相同
 *   区别在于操作方式：栈只能在头部进行插入和删除
 *
 * 对比顺序栈:
 *   顺序栈: data[MAXSIZE] + top指针
 *   链式栈: 链表节点 + next指针
 */
typedef struct stack
{
	ElemType data;      // 数据域
	struct stack *next; // 指针域
}Stack;

/**
 * 函数: initStack
 * 功能: 初始化链式栈（创建带头节点的空栈）
 *
 * 参数: 无
 *
 * 返回值: 返回指向头节点的指针
 *
 * 算法思路:
 *   1. 为头节点分配内存
 *   2. 头节点的data可以不初始化（不存储有效数据）
 *   3. 头节点的next设置为NULL，表示空栈
 *   4. 返回头节点指针
 *
 * 时间复杂度: O(1)
 * 空间复杂度: O(1)
 *
 * 注意事项:
 *   - 使用带头节点的链表，简化插入和删除操作
 *   - 头节点本身不存储栈元素
 *   - head->next == NULL 表示空栈
 *   - head->next指向栈顶元素
 */
Stack* initStack()
{
	// 为头节点分配内存
	Stack *s = (Stack*)malloc(sizeof(Stack));

	// 头节点数据域（不存储有效数据）
	s->data = 0;

	// 头节点next设置为NULL，表示空栈
	s->next = NULL;

	return s;
}

/**
 * 函数: isEmpty
 * 功能: 判断链式栈是否为空
 *
 * 参数:
 *   @param s - 指向头节点的指针
 *
 * 返回值:
 *   1 - 栈为空
 *   0 - 栈不为空
 *
 * 算法思路:
 *   检查头节点的next是否为NULL
 *
 * 时间复杂度: O(1)
 * 空间复杂度: O(1)
 *
 * 注意:
 *   链式栈判空条件: s->next == NULL
 *   顺序栈判空条件: s->top == -1
 */
int isEmpty(Stack *s)
{
	if (s->next == NULL)
	{
		printf("空的\n");
		return 1;
	}
	else
	{
		return 0;
	}
}

/**
 * 函数: push
 * 功能: 进栈操作（将元素压入栈顶）
 *
 * 参数:
 *   @param s - 指向头节点的指针
 *   @param e - 要入栈的元素
 *
 * 返回值: 1 - 入栈成功
 *
 * 算法思路:
 *   1. 创建新节点并分配内存
 *   2. 新节点的data赋值为e
 *   3. 新节点的next指向原栈顶（s->next）
 *   4. 头节点的next指向新节点
 *   （实际上就是链表的头插法）
 *
 * 时间复杂度: O(1)
 * 空间复杂度: O(1)
 *
 * 关键点:
 *   - 链式栈的push就是链表的头插法
 *   - 新元素总是插入在头节点之后，成为新的栈顶
 *   - 理论上永远不会栈满（除非系统内存耗尽）
 *
 * 示例:
 *   原栈: head → [20] → [10] → NULL
 *   push(s, 30)
 *   结果: head → [30] → [20] → [10] → NULL
 */
int push(Stack *s, ElemType e)
{
	// 1. 创建新节点
	Stack *p = (Stack*)malloc(sizeof(Stack));

	// 2. 新节点赋值
	p->data = e;

	// 3. 新节点的next指向原栈顶
	p->next = s->next;

	// 4. 头节点的next指向新节点（新节点成为新的栈顶）
	s->next = p;

	return 1;
}

/**
 * 函数: pop
 * 功能: 出栈操作（弹出栈顶元素）
 *
 * 参数:
 *   @param s - 指向头节点的指针
 *   @param e - 指向用于存储出栈元素的变量指针
 *
 * 返回值:
 *   1 - 出栈成功
 *   0 - 出栈失败（栈空）
 *
 * 算法思路:
 *   1. 检查栈是否为空
 *   2. 取出栈顶节点的数据
 *   3. 保存栈顶节点指针
 *   4. 头节点的next指向栈顶的next（跳过栈顶节点）
 *   5. 释放原栈顶节点的内存
 *
 * 时间复杂度: O(1)
 * 空间复杂度: O(1)
 *
 * 关键点:
 *   - 链式栈的pop需要释放节点内存
 *   - 顺序栈的pop只需要移动top指针
 *   - 必须先保存要删除节点的指针，再修改链接，最后释放内存
 *
 * 示例:
 *   原栈: head → [30] → [20] → [10] → NULL
 *   pop(s, &e)
 *   结果: head → [20] → [10] → NULL, e=30
 */
int pop(Stack *s, ElemType *e)
{
	// 1. 检查栈是否为空
	if(s->next == NULL)
	{
		printf("空的\n");
		return 0;
	}

	// 2. 取出栈顶元素的数据
	*e = s->next->data;

	// 3. 保存栈顶节点指针（稍后释放）
	Stack *q = s->next;

	// 4. 头节点的next指向原栈顶的next（移除栈顶）
	s->next = q->next;

	// 5. 释放原栈顶节点的内存
	free(q);

	return 1;
}

/**
 * 函数: getTop
 * 功能: 获取栈顶元素（不删除）
 *
 * 参数:
 *   @param s - 指向头节点的指针
 *   @param e - 指向用于存储栈顶元素的变量指针
 *
 * 返回值:
 *   1 - 获取成功
 *   0 - 获取失败（栈空）
 *
 * 算法思路:
 *   检查栈是否为空，若不为空则返回s->next->data
 *   不修改栈的结构
 *
 * 时间复杂度: O(1)
 * 空间复杂度: O(1)
 *
 * 与pop的区别:
 *   - pop: 取出并删除栈顶（需要free）
 *   - getTop: 只查看栈顶，不删除（不需要free）
 */
int getTop(Stack *s, ElemType *e)
{
	// 检查栈是否为空
	if (s->next == NULL)
	{
		printf("空的\n");
		return 0;
	}

	// 获取栈顶元素，不改变栈结构
	*e = s->next->data;

	return 1;
}

/**
 * 主函数: 测试链式栈的基本操作
 *
 * 测试流程:
 *   1. 初始化链式栈
 *   2. 依次压入10, 20, 30
 *   3. 弹出栈顶元素并打印（应输出30）
 *   4. 获取栈顶元素并打印（应输出20）
 *
 * 栈的变化过程:
 *   初始: head → NULL
 *   push(10): head → [10] → NULL
 *   push(20): head → [20] → [10] → NULL
 *   push(30): head → [30] → [20] → [10] → NULL
 *   pop(): head → [20] → [10] → NULL, 输出30
 *   getTop(): head → [20] → [10] → NULL, 输出20
 *
 * 内存管理:
 *   本例未完全释放所有节点内存
 *   完整的清理应该:
 *   1. 循环pop所有元素
 *   2. 释放头节点
 */
int main()
{
	// 初始化链式栈
	Stack *s = initStack();

	// 压入三个元素
	push(s, 10);
	push(s, 20);
	push(s, 30);

	// 出栈并打印
	ElemType e;
	pop(s, &e);
	printf("%d\n", e);  // 输出: 30

	// 获取栈顶元素并打印
	getTop(s, &e);
	printf("%d\n", e);  // 输出: 20

	system("pause");
	return 0;
}

